// Maps icon names (strings stored in data files / API responses) to Lucide components.
// Keeping icons as strings in data makes the data JSON-serializable and API-friendly.
import {
  Search,
  Share2,
  MousePointerClick,
  PenTool,
  Code2,
  Palette,
  Mail,
  TrendingUp,
  Target,
  BarChart3,
  Users,
  Zap,
  ShieldCheck,
  Sparkles,
  Heart,
  Lightbulb,
  Eye,
  Trophy,
  Award,
  Rocket,
  Layers,
  MapPin,
  Wallet,
  Headphones,
  Cpu,
  Megaphone,
  Clapperboard,
  MessageCircle,
  Smartphone,
  Globe,
  Circle,
} from "lucide-react";

const ICONS = {
  Search,
  Share2,
  MousePointerClick,
  PenTool,
  Code2,
  Palette,
  Mail,
  TrendingUp,
  Target,
  BarChart3,
  Users,
  Zap,
  ShieldCheck,
  Sparkles,
  Heart,
  Lightbulb,
  Eye,
  Trophy,
  Award,
  Rocket,
  Layers,
  MapPin,
  Wallet,
  Headphones,
  Cpu,
  Megaphone,
  Clapperboard,
  MessageCircle,
  Smartphone,
  Globe,
};

export default function Icon({ name, size = 24, ...props }) {
  const Component = ICONS[name] || Circle;
  return <Component size={size} aria-hidden="true" {...props} />;
}
